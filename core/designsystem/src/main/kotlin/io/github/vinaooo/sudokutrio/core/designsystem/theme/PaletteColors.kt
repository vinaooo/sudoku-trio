/** [color]'s scheme, light or [dark]. Blue is the brand's. */
fun paletteScheme(color: ThemeColor, dark: Boolean): ColorScheme {
    val (light, darkScheme) = when (color) {
        ThemeColor.GREEN -> GreenColors.light to GreenColors.dark
        ThemeColor.TEAL -> TealColors.light to TealColors.dark
        ThemeColor.BLUE -> BlueColors.light to BlueColors.dark
        ThemeColor.INDIGO -> IndigoColors.light to IndigoColors.dark
        ThemeColor.PURPLE -> PurpleColors.light to PurpleColors.dark
        ThemeColor.PINK -> PinkColors.light to PinkColors.dark
        ThemeColor.RED -> RedColors.light to RedColors.dark
        ThemeColor.ORANGE -> OrangeColors.light to OrangeColors.dark
    }
    return if (dark) darkScheme else light
}

